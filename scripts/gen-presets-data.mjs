import assert from 'node:assert/strict';
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const index = JSON.parse(readFileSync(new URL('../presets/index.json', import.meta.url), 'utf8'));
const shapes = [], rows = [];
// All native themes repeat the same field names, with a few optional roles.
// Store each distinct object shape once and pack the original leaf values
// against it. Arrays (e.g. tags) are leaves, and nothing is normalized.
function shapeOf(value, values) {
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, shapeOf(child, values)]));
  }
  values.push(value);
  return null;
}
for (const preset of index.presets) {
  assert.match(preset.slug, /^[a-z0-9][a-z0-9-]+$/u);
  const pair = [];
  for (const v of ['light', 'dark']) {
    const file = preset.variants[v].file;
    assert.match(file, /^[a-z0-9][a-z0-9-]+\.json$/u);
    const theme = JSON.parse(readFileSync(new URL(`../presets/${file}`, import.meta.url), 'utf8'));
    assert.equal(theme.metadata.variant, v, file);
    const values = [];
    const shape = JSON.stringify(shapeOf(theme, values));
    if (!shapes.includes(shape)) shapes.push(shape);
    pair.push(`${v}: decode(${shapes.indexOf(shape)}, ${JSON.stringify(values)})`);
  }
  rows.push(`  ${JSON.stringify(preset.slug)}: { ${pair.join(', ')} },`);
}
const path = fileURLToPath(new URL('../src/data/preset-definitions.mjs', import.meta.url));
const content = `// Generated by scripts/gen-presets-data.mjs.
const shapes = [
${shapes.map((shape) => `  ${shape},`).join('\n')}
];
function decode(index, values) {
  let offset = 0;
  const read = (node) => node === null ? values[offset++] :
    Object.fromEntries(Object.entries(node).map(([key, child]) => [key, read(child)]));
  return read(shapes[index]);
}

export const presetDefinitions = {
${rows.join('\n')}
};
`;
if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
  const tmp = `${path}.${process.pid}.tmp`;
  writeFileSync(tmp, content, { flag: 'wx' });
  renameSync(tmp, path);
}
